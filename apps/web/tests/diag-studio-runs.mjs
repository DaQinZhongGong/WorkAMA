import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE || '/usr/bin/chromium', args: ['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'] })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage()
let token = null
page.on('response', async response => { const u=response.url(); if((u.includes('/auth/login')||u.includes('/auth/refresh'))&&response.ok()){ try{const b=await response.json(); if(b.access_token) token=b.access_token}catch{}}})
page.on('console', m=>console.log('console',m.type(),m.text()))
page.on('pageerror', e=>console.log('pageerror',e.message))
page.on('response', r=>{ if(r.status()>=400) console.log('response',r.status(),r.url())})
await page.route('http://localhost:20200/**', route=>{const o=route.request().url(); if(o.includes('/auth/refresh')&&token) return route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({access_token:token})}); return route.continue({url:o.replace('http://localhost:20200','http://platform-api:8000')})})
await page.routeWebSocket('ws://localhost:20201/**', ws=>ws.connectToServer(ws.url().replace('ws://localhost:20201','ws://agent-server:8001')))
await page.goto('http://localhost:3000/login',{waitUntil:'domcontentloaded'})
await page.locator('#email').fill('tester@workama.example.com')
await page.locator('#password').fill('WorkAMA-Test-2026!')
await page.locator('button[type="submit"]').click()
await page.waitForURL(/\/chat|\/onboarding|\/admin/)
await page.goto('http://localhost:3000/studio/apps',{waitUntil:'networkidle'})
const href = await page.locator('a[href^="/studio/apps/ast_"]').first().getAttribute('href')
console.log('href', href)
await page.goto(`http://localhost:3000${href}/runs`,{waitUntil:'networkidle'})
await page.waitForTimeout(2000)
console.log('url', page.url())
console.log('h', await page.locator('h1,h2').allInnerTexts())
console.log('body', (await page.locator('body').innerText()).slice(0,2000))
await page.screenshot({path:'/tmp/studio-runs-diag.png'})
await browser.close()
